const HERE = dirname(fileURLToPath(import.meta.url));
// Single source of truth for git plumbing — same pattern as b-pr-improved.
const PREFLIGHT = join(HERE, "..", "..", "skills", "git-commit", "scripts", "commit-preflight.ts");

// ---------- git helpers ----------

function execGit(args: string[], cwd: string, env?: NodeJS.ProcessEnv): string {
  try {
    return execFileSync("git", args, {
      cwd,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
      env: { ...process.env, ...env },
    });
  } catch (e: unknown) {
    const err = e as Error & { stderr?: Buffer };
    throw new Error(`git ${args.join(" ")} failed: ${err.stderr?.toString().trim() || err.message}`);
  }
}

// tryGit runs a git command without throwing — returns ok flag plus stdout.
// Used for read-only checks (status, log, diff --cached --name-only after a hook).
function tryGit(args: string[], cwd: string): { ok: boolean; stdout: string } {
  try {
    return { ok: true, stdout: execGit(args, cwd) };
  } catch {
    return { ok: false, stdout: "" };
  }
}

// ---------- preflight ----------

interface DraftBlock {
  title: string;
  body: string;
}

interface Preflight {
  code: number;
  json: Record<string, unknown> | null;
}

async function runPreflight(args: string[], cwd: string): Promise<Preflight> {
  const { code, stdout } = await execFileCaptured("bun", [PREFLIGHT, ...args], cwd);
  let json: Record<string, unknown> | null = null;
  try {
    json = stdout.trim() ? (JSON.parse(stdout) as Record<string, unknown>) : null;
  } catch {
    json = null;
  }
  return { code, json };
}

// ---------- inline model invocation ----------

async function runModelSession(
  cwd: string,
  tools: string[],
  prompt: string,
  modelOverride: string | undefined,
  onActivity: (event: ActivityEvent) => void,
  timeoutMs = 60_000,
): Promise<string> {
  return runOmpModelSession({ cwd, tools, prompt, modelOverride, timeoutMs, onActivity });
}


// ---------- draft I/O ----------

function draftPathFor(subjectFolder: string | null): string {
  return subjectFolder ? join(subjectFolder, "draft-commit.md") : ".context/draft-commit.md";
}

// Unfilled draft sentinel is $TITLE / $BODY. Angle brackets document
// shape in prose only. `<short summary>` is a legacy file stub that
// looks like a Conventional Commit (and like XML) — still refused.
const COMMIT_PLACEHOLDER_RE = /\$TITLE|\$BODY|<short summary/i;

export function hasCommitPlaceholders(text: string): boolean {
  return COMMIT_PLACEHOLDER_RE.test(text);
}

// Write a stub draft-commit.md. ## Title / ## Body are $TITLE / $BODY —
// not a fake `feat: <short summary>` line. Re-running this command must
// not treat those sentinels as a commitable message.
export function fallbackDraft(
  cwd: string,
  subjectFolder: string | null,
  diff: string,
  stagedFiles: string[],
  extraContext: string,
  reason: string,
): string {
  const relPath = draftPathFor(subjectFolder);
  const path = join(cwd, relPath);
  const ctx = extraContext.trim() || "(none)";
  const files = stagedFiles.length ? stagedFiles.join("\n") : "(none)";
  const truncatedDiff = diff.length > 8000 ? diff.slice(0, 8000) + "\n... (truncated)" : diff;
  const body = [
    "<!--",
    `Auto-generated by b-commit-improved on ${new Date().toISOString()}.`,
    `Reason: ${reason}`,
    "",
    "Replace $TITLE and $BODY (format: type(optional-scope): summary), then re-run:",
    "  /b-commit-improved   (drafts via model, or commits a filled title)",
    "  /b-commit            (agent replaces the sentinels, then commits)",
    "-->",
    "",
    "## Title",
    "",
    "$TITLE",
    "",
    "## Body",
    "",
    "$BODY",
    "",
    "### User context",
    ctx,
    "",
    "### Staged files",
    "```",
    files,
    "```",
    "",
    "### Staged diff (truncated)",
    "```diff",
    truncatedDiff,
    "```",
    "",
  ].join("\n");
  writeFileSync(path, body, "utf-8");
  return relPath;
}

// Persist a successful model-drafted message as a draft-commit.md (used by
// --dry-run so the user has an artifact they can re-run against).
function writeDraft(cwd: string, subjectFolder: string | null, title: string, body: string): string {
  const relPath = draftPathFor(subjectFolder);
  writeFileSync(join(cwd, relPath), `## Title\n\n${title}\n\n## Body\n\n${body}\n`, "utf-8");
  return relPath;
}

function persistDryRunDraft(
  cwd: string,
  subjectFolder: string | null,
  title: string,
  body: string,
  notify: Notify,
): void {
  const existing = draftPathFor(subjectFolder);
  if (existsSync(join(cwd, existing))) {
    notify(`[dry-run] Left the existing draft at ${existing} untouched.`, "info");
    return;
  }
  const path = writeDraft(cwd, subjectFolder, title, body);
  notify(`[dry-run] Wrote draft to ${path} (re-run without --dry-run to commit).`, "info");
}

// Best-effort draft deletion. Tolerates ENOENT (race with another process).
function deleteDraft(path: string): void {
  try {
    unlinkSync(path);
  } catch {
    // already gone
  }
}

// ---------- args ----------

interface Options {
  force: boolean;
  noDraft: boolean;
  dryRun: boolean;
  model?: string;
  extraContext: string;
}

function parseArgs(args: string): Options {
  const tokens = args.split(/\s+/).filter(Boolean);
  const get = (flag: string): string | undefined => {
    const i = tokens.indexOf(flag);
    if (i === -1 || i + 1 >= tokens.length) return undefined;
    const next = tokens[i + 1];
    // Never consume another option as this one's value; fall through to detection.
    if (next.startsWith("-")) return undefined;
    return next;
  };
  const consumed = new Set<number>();
  for (let i = 0; i < tokens.length; i++) {
    if (tokens[i] === "--force" || tokens[i] === "--no-draft" || tokens[i] === "--dry-run") {
      consumed.add(i);
    } else if (tokens[i] === "--model") {
      consumed.add(i);
      if (i + 1 < tokens.length) consumed.add(i + 1);
    }
  }
  const extraContext = tokens.filter((_, i) => !consumed.has(i)).join(" ").trim();
  return {
    force: tokens.includes("--force"),
    noDraft: tokens.includes("--no-draft"),
    dryRun: tokens.includes("--dry-run"),
    model: get("--model"),
    extraContext,
  };
}

// ---------- model: draft commit message ----------

function buildPrompt(
  cwd: string,
  diff: string,
  stagedFiles: string[],
  currentBranch: string,
  extraContext: string,
): string {
  const repoName = cwd.split("/").pop() || "repo";
  const files = stagedFiles.length ? stagedFiles.join("\n") : "(none)";
  const userCtx = extraContext.trim() || "(none)";
  const truncatedDiff = diff.length > 8000 ? diff.slice(0, 8000) + "\n... (truncated)" : diff;
  return (
    `You are drafting a Conventional Commits commit message for the staged changes below.\n\n` +
    `Repository: ${repoName}\n` +
    `Current branch: ${currentBranch}\n` +
    `Extra context from the user: ${userCtx}\n\n` +
    `Staged files:\n${files}\n\n` +
    `Staged diff (truncated to 8000 chars):\n${truncatedDiff}\n\n` +
    `Return a JSON object with EXACTLY two string fields, no markdown fencing:\n` +
    `{"title":"feat(scope): add retry on timeout","body":"Retries hide transient API flakes."}\n\n` +
    `Rules:\n` +
    `- Title format: type(optional-scope): summary (<=72 chars)\n` +
    `- Type ∈ {feat, fix, refactor, perf, docs, test, build, ci, chore, style, revert}\n` +
    `- If breaking, include \`BREAKING CHANGE: <note>\` in body\n` +
    `- Do NOT emit $TITLE, $BODY, or leftover <short summary>\n` +
    `- Body is optional — empty string is fine for trivial changes\n`
  );
}

/**
 * Pull the first JSON object out of a model response: strip optional
 * ```json fences, then slice from the first `{` to the last `}` and
 * parse. Null when no object is present or the slice is not JSON.
 */
function extractJsonObject(raw: string): Record<string, unknown> | null {
  const trimmed = raw.trim();
  const fenced = trimmed.match(/^```(?:json)?\s*([\s\S]*?)\s*```$/);
  const body = fenced ? fenced[1] : trimmed;
  const start = body.indexOf("{");
  const end = body.lastIndexOf("}");
  if (start < 0 || end < 0 || end <= start) return null;
  try {
    const parsed: unknown = JSON.parse(body.slice(start, end + 1));
    return parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}

function parseModelResponse(raw: string): DraftBlock | null {
  const parsed = extractJsonObject(raw);
  if (!parsed) return null;
  const title = parsed.title;
  const bodyField = parsed.body;
  if (typeof title !== "string" || title.trim() === "") return null;
  return {
    title: title.trim(),
    body: typeof bodyField === "string" ? bodyField.trim() : "",
  };
}

async function draftFromModel(
  cwd: string,
  diff: string,
  stagedFiles: string[],
  currentBranch: string,
  extraContext: string,
  modelOverride: string | undefined,
  dryRun: boolean,
  subjectFolder: string | null,
  onActivity: (event: ActivityEvent) => void,
): Promise<DraftBlock | null> {
  const prompt = buildPrompt(cwd, diff, stagedFiles, currentBranch, extraContext);
  let raw = "";
  try {
    raw = await runModelSession(cwd, ["read"], prompt, modelOverride, onActivity);
  } catch (e: unknown) {
    if (!dryRun) {
      fallbackDraft(cwd, subjectFolder, diff, stagedFiles, extraContext, `model call failed: ${(e as Error).message}`);
    }
    return null;
  }
  const parsed = parseModelResponse(raw);
  if (!parsed) {
    if (!dryRun) {
      const snippet = raw.slice(0, 200).replace(/\n/g, " ");
      fallbackDraft(cwd, subjectFolder, diff, stagedFiles, extraContext, `model returned an unparseable response (first 200 chars: ${snippet})`);
    }
    return null;
  }
  // The command handler writes a new dry-run draft. It must not overwrite
  // a pre-existing draft-commit.md, so this function does not write.
  return parsed;
}

// ---------- command handler ----------

type Notify = (msg: string, level?: "info" | "warning" | "error") => void;

interface CommandUI {
  notify: Notify;
  setStatus?: (key: string, text?: string) => void;
  setWorkingMessage?: (message?: string) => void;
  setWidget?: (
    key: string,
    content: string[] | undefined,
    options?: { placement?: "aboveEditor" | "belowEditor" },
  ) => void;
}

/** Preflight JSON fields the command handler consumes. */
interface PreflightData {
  currentBranch: string;
  subjectFolder: string | null;
  draftPath: string | null;
  draftFromDisk: DraftBlock | null;
  stagedFiles: string[];
  diff: string;
}

/**
 * Step 1: run the preflight script. Returns null (after notifying) when the
 * command must stop — protected branch, nothing staged, or preflight failure.
 */
async function preflightOrNotify(opts: Options, cwd: string, notify: Notify): Promise<PreflightData | null> {
  const pfArgs: string[] = [];
  if (opts.force) pfArgs.push("--force");
  if (opts.noDraft) pfArgs.push("--no-draft");
  if (opts.dryRun) pfArgs.push("--dry-run");

  const pf = await runPreflight(pfArgs, cwd);
  if (pf.code === 2) {
    const branch = (pf.json?.current_branch as string) ?? "unknown";
    notify(`Protected branch '${branch}' — re-run with --force to commit here directly.`, "warning");
    return null;
  }
  if (pf.code === 3) {
    notify("Nothing staged. Stage changes first, then re-run.", "warning");
    return null;
  }
  if (pf.code !== 0 || !pf.json) {
    notify(`Preflight failed (exit ${pf.code}): ${(pf.json?.error as string) ?? "no output"}`, "warning");
    return null;
  }
  const {
    current_branch: currentBranch,
    subject_folder: subjectFolder,
    draft_path: draftPath,
    draft: draftFromDisk,
    staged_files: stagedFiles,
    diff,
  } = pf.json as {
    current_branch: string;
    subject_folder: string | null;
    draft_path: string | null;
    draft: DraftBlock | null;
    staged_files: string[];
    diff: string;
  };
  return { currentBranch, subjectFolder, draftPath, draftFromDisk, stagedFiles, diff };
}

/** The commit message once resolved, plus where it came from. */
interface ResolvedMessage {
  title: string;
  body: string;
  source: "draft" | "model";
}

/**
 * Step 2: resolve {title, body} from the on-disk draft or the model.
 * Returns null (after notifying) when no message could be produced.
 */
async function resolveMessage(
  opts: Options,
  data: PreflightData,
  cwd: string,
  activity: Activity,
  notify: Notify,
): Promise<ResolvedMessage | null> {
  if (data.draftFromDisk && data.draftFromDisk.title.trim() !== "" && !opts.noDraft) {
    return { title: data.draftFromDisk.title, body: data.draftFromDisk.body, source: "draft" };
  }
  activity.phase("Drafting commit message…");
  const drafted = await draftFromModel(
    cwd,
    data.diff,
    data.stagedFiles,
    data.currentBranch,
    opts.extraContext,
    opts.model,
    opts.dryRun,
    data.subjectFolder,
    activity.ingest,
  );
  if (!drafted) {
    // In a normal run, fallbackDraft inside draftFromModel already wrote
    // a stub draft-commit.md. In --dry-run, no file is written (per
    // draftFromModel's contract), so the previous "Drafted to ${path}.
    // Re-run ... to commit" message was misleading — it claimed a draft
    // existed when it didn't. Tell the user the real story per mode.
    if (opts.dryRun) {
      notify(
        `[dry-run] No model available and no draft on disk. Re-run /b-commit-improved (or /b-commit) once a model is available to draft.`,
        "info",
      );
    } else {
      const path = draftPathFor(data.subjectFolder);
      notify(`Wrote a stub draft to ${path} ($TITLE/$BODY sentinels). Replace them or re-run once a model can draft.`, "info");
    }
    return null;
  }
  return { title: drafted.title, body: drafted.body, source: "model" };
}

/**
 * Step 5: run the commit. Hooks may auto-stage files mid-commit; when the
 * first attempt fails but the index now has entries, retry once. Returns
 * false (after notifying) when the commit did not land.
 */
function commitWithRetry(commitArgs: string[], cwd: string, notify: Notify): boolean {
  try {
    execGit(commitArgs, cwd);
  } catch (e: unknown) {
    const msg = (e as Error).message;
    const stagedNow = tryGit(["diff", "--cached", "--name-only"], cwd);
    if (stagedNow.ok && stagedNow.stdout.trim() !== "") {
      try {
        execGit(commitArgs, cwd);
      } catch (e2: unknown) {
        notify(`git commit failed (after hook auto-stage retry): ${(e2 as Error).message}`, "warning");
        return false;
      }
    } else {
      notify(`git commit failed: ${msg}`, "warning");
      return false;
    }
  }
  return true;
}

/**
 * Step 6: delete the committed draft and amend the deletion into the commit.
 * A lost race (another process deleting it first) is tolerated — the commit
 * stands without the amend.
 */
function cleanupDraft(draftPath: string | null, cwd: string): void {
  if (draftPath && existsSync(draftPath)) {
    deleteDraft(draftPath);
    try {
      execGit(["add", "--", draftPath], cwd);
    } catch {
      // Race: another process deleted it first. Commit is fine without the amend.
    }
    try {
      execGit(["commit", "--amend", "--no-edit"], cwd, { GIT_EDITOR: "true" });
    } catch {
      // Same race — commit stands as-is.
    }
  }
}

/**
 * Step 7: paranoid verify — the committed message should never contain
 * sentinels (step 3 refuses them), but if it does, amend with explicit values.
 */
function verifyCommitMessage(message: ResolvedMessage, cwd: string, notify: Notify): void {
  const verifyRaw = tryGit(["log", "-1", "--format=%B"], cwd);
  const committed = verifyRaw.ok ? verifyRaw.stdout.trim() : "";
  if (hasCommitPlaceholders(committed)) {
    try {
      execGit(["commit", "--amend", "-m", message.title, "-m", message.body], cwd, { GIT_EDITOR: "true" });
      notify("⚠️ commit message contained a $TITLE/$BODY placeholder; amended with explicit values.", "warning");
    } catch (e: unknown) {
      notify(`verify-pass amend failed: ${(e as Error).message}`, "warning");
    }
  }
}

/** Step 8: report the landed commit plus branch status. */
function reportSuccess(message: ResolvedMessage, cwd: string, activity: Activity, notify: Notify): void {
  notify(`✅ ${message.title}${message.body ? "\n" + message.body : ""}`, "info");
  const status = tryGit(["status", "-sb"], cwd);
  if (status.ok) notify(status.stdout.trimEnd(), "info");
  const log = tryGit(["log", "-1", "--oneline"], cwd);
  if (log.ok) notify(log.stdout.trimEnd(), "info");
  activity.succeed("done");
}

async function runBCommitImproved(
  args: string,
  ctx: { cwd: string; ui: CommandUI },
): Promise<void> {
  const cwd = ctx.cwd;
  const notify = ctx.ui.notify;
  const opts = parseArgs(args);
  const activity = createActivity({ ui: ctx.ui, command: "b-commit-improved" });

  try {
    // 1. Preflight
    activity.phase("preflight…");
    const data = await preflightOrNotify(opts, cwd, notify);
    if (!data) return;

    // 2. Resolve {title, body}. Commit in line once we have it.
    const message = await resolveMessage(opts, data, cwd, activity, notify);
    if (!message) return;

    // 3. Pre-commit safety: refuse leftover template tokens.
    if (hasCommitPlaceholders(message.title) || hasCommitPlaceholders(message.body)) {
      notify("Refusing to commit: title or body contains $TITLE, $BODY, or leftover <short summary>. Fix the draft and re-run.", "warning");
      return;
    }

    // 4. --dry-run: preview, optionally write the draft.
    if (opts.dryRun) {
      const firstBodyLine = message.body.split("\n", 1)[0] ?? "";
      notify(`[dry-run] ${message.title} — ${firstBodyLine}`, "info");
      if (message.source === "model") persistDryRunDraft(cwd, data.subjectFolder, message.title, message.body, notify);
      return;
    }

    // 5. Commit. Hooks may have auto-staged files — retry once on failure if so.
    activity.phase("Committing…");
    const commitArgs = message.body ? ["commit", "-m", message.title, "-m", message.body] : ["commit", "-m", message.title];
    if (!commitWithRetry(commitArgs, cwd, notify)) return;

    // 6. Success cleanup: delete the draft and amend the deletion into the commit.
    cleanupDraft(data.draftPath, cwd);

    // 7. Verify
    verifyCommitMessage(message, cwd, notify);

    // 8. Final output
    reportSuccess(message, cwd, activity, notify);
  } catch (e: unknown) {
    activity.fail(`error: ${(e as Error).message}`);
    throw e;
  } finally {
    activity.dispose();
  }
}

// ---------- wiring ----------

export function wire(pi: ExtensionAPI): void {
  pi.registerCommand("b-commit-improved", {
    description: "Deterministic Conventional Commits: preflight → model draft → commit, with $TITLE/$BODY fallback when no model",
    getArgumentCompletions(prefix: string) {
      return ["--force", "--no-draft", "--dry-run", "--model"]
        .filter((o) => o.startsWith(prefix))
        .map((o) => ({ value: o, label: o }));
    },
    handler: async (args: string, ctx: { cwd: string; ui: CommandUI }) => {
      await runBCommitImproved(args, ctx);
    },
  });
}
