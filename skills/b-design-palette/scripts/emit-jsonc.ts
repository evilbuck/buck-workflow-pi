import type { DesignBriefDoc } from "./palette-build.js";

function indent(level: number): string {
  return "  ".repeat(level);
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function emitObject(
  obj: Record<string, string>,
  level: number,
): string[] {
  const keys = Object.keys(obj);
  const lines = ["{"];
  keys.forEach((key, i) => {
    const comma = i < keys.length - 1 ? "," : "";
    lines.push(`${indent(level + 1)}${quote(key)}: ${quote(obj[key])}${comma}`);
  });
  lines.push(`${indent(level)}}`);
  return lines;
}

function emitNamedScale(
  name: string,
  scale: Record<string, string>,
  level: number,
  trailingComma: boolean,
): string[] {
  const lines = [
    `${indent(level)}// ${name} tint scale (50–950)`,
    `${indent(level)}${quote(name)}: {`,
  ];
  const keys = Object.keys(scale);
  keys.forEach((key, i) => {
    const comma = i < keys.length - 1 ? "," : "";
    lines.push(`${indent(level + 1)}${quote(key)}: ${quote(scale[key])}${comma}`);
  });
  lines.push(`${indent(level)}}${trailingComma ? "," : ""}`);
  return lines;
}

/** Stable, commented JSONC for design-brief.jsonc. */
export function emitDesignBriefJsonc(doc: DesignBriefDoc): string {
  const lines: string[] = [];
  lines.push("// design-brief.jsonc — generated by b-design-palette (deterministic OKLCH palette)");
  lines.push("// Do not hand-edit hex values; re-run the script with updated inputs.");
  lines.push("{");

  lines.push(`${indent(1)}// ── UI meta ──────────────────────────────────────────────────────────────`);
  lines.push(`${indent(1)}${quote("name")}: ${quote(doc.name)},`);
  lines.push(`${indent(1)}${quote("version")}: ${doc.version},`);
  lines.push(`${indent(1)}${quote("meta")}: {`);
  if (doc.meta.purpose) {
    lines.push(`${indent(2)}${quote("purpose")}: ${quote(doc.meta.purpose)},`);
  }
  if (doc.meta.audience) {
    lines.push(`${indent(2)}${quote("audience")}: ${quote(doc.meta.audience)},`);
  }
  lines.push(`${indent(2)}${quote("generated_by")}: ${quote(doc.meta.generated_by)}`);
  lines.push(`${indent(1)}},`);

  lines.push(`${indent(1)}// ── Inputs used ───────────────────────────────────────────────────────────`);
  lines.push(`${indent(1)}${quote("inputs")}: {`);
  lines.push(`${indent(2)}${quote("brand")}: ${quote(doc.inputs.brand)},`);
  lines.push(
    `${indent(2)}${quote("secondary")}: ${doc.inputs.secondary ? quote(doc.inputs.secondary) : "null"},`,
  );
  lines.push(
    `${indent(2)}${quote("accent")}: ${doc.inputs.accent ? quote(doc.inputs.accent) : "null"},`,
  );
  lines.push(`${indent(2)}${quote("scheme")}: ${quote(doc.inputs.scheme)},`);
  lines.push(`${indent(2)}${quote("neutral")}: ${quote(doc.inputs.neutral)},`);
  lines.push(`${indent(2)}${quote("dark")}: ${doc.inputs.dark ? "true" : "false"},`);
  lines.push(
    `${indent(2)}${quote("status_overrides")}: ${JSON.stringify(doc.inputs.status_overrides)}`,
  );
  lines.push(`${indent(1)}},`);

  lines.push(`${indent(1)}// ── Scales ────────────────────────────────────────────────────────────────`);
  lines.push(`${indent(1)}${quote("scales")}: {`);
  const scaleNames = Object.keys(doc.scales) as Array<keyof typeof doc.scales>;
  scaleNames.forEach((name, i) => {
    lines.push(...emitNamedScale(name, doc.scales[name], 2, i < scaleNames.length - 1));
  });
  lines.push(`${indent(1)}},`);

  lines.push(`${indent(1)}// ── Semantic roles (light) ───────────────────────────────────────────────`);
  lines.push(`${indent(1)}${quote("roles")}: {`);
  lines.push(`${indent(2)}${quote("light")}: {`);
  const lightKeys = Object.keys(doc.roles.light);
  lightKeys.forEach((key, i) => {
    const comma = i < lightKeys.length - 1 ? "," : "";
    lines.push(`${indent(3)}${quote(key)}: ${quote(doc.roles.light[key])}${comma}`);
  });
  if (doc.roles.dark) {
    lines.push(`${indent(2)}},`);
    lines.push(`${indent(2)}// ── Semantic roles (dark) ────────────────────────────────────────────────`);
    lines.push(`${indent(2)}${quote("dark")}: {`);
    const darkKeys = Object.keys(doc.roles.dark);
    darkKeys.forEach((key, i) => {
      const comma = i < darkKeys.length - 1 ? "," : "";
      lines.push(`${indent(3)}${quote(key)}: ${quote(doc.roles.dark![key])}${comma}`);
    });
    lines.push(`${indent(2)}}`);
  } else {
    lines.push(`${indent(2)}}`);
  }
  lines.push(`${indent(1)}},`);

  lines.push(`${indent(1)}// ── Contrast report (WCAG AA ≥ 4.5) ───────────────────────────────────────`);
  lines.push(`${indent(1)}${quote("contrast")}: [`);
  doc.contrast.forEach((entry, i) => {
    const comma = i < doc.contrast.length - 1 ? "," : "";
    lines.push(
      `${indent(2)}{ ${quote("pair")}: ${quote(entry.pair)}, ${quote("foreground")}: ${quote(entry.foreground)}, ${quote("background")}: ${quote(entry.background)}, ${quote("ratio")}: ${entry.ratio}, ${quote("pass_aa")}: ${entry.pass_aa ? "true" : "false"} }${comma}`,
    );
  });
  lines.push(`${indent(1)}]`);
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

// Keep emitObject exported for tests that want a raw map dump.
export { emitObject };
